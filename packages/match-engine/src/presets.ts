export function defaultPlan(formation = '4-3-3'): TacticalPlan {
  const f = FORMATIONS[formation]!;
  return {
    shapes: { inPossession: f.inPossession, outOfPossession: f.outOfPossession },
    team: {
      buildUp: 'mixed',
      tempo: 3,
      width: 3,
      risk: 3,
      progression: 'vertical',
      finalThird: { crosses: 3, throughBalls: 3, boxPresence: 3, shootFromDistance: 3 },
      onLoss: 'counterPress',
      onWin: 'counter',
      block: 'mid',
      lineHeight: 3,
      compactness: 3,
      pressIntensity: 3,
      pressTriggers: ['backPass', 'poorTouch'],
      forceDirection: null,
      offsideTrap: false,
      timeWasting: 0,
      restDefence: 3,
    },
    roles: [...f.roles],
    individual: Array.from({ length: 11 }, () => ({})),
    marking: [],
    setPieces: {},
  };
}

/** A coach with every dimension at `level` (ADR-019), with optional overrides. */
export const coachOf = (level = 60, over: Partial<Coach> = {}): Coach => ({
  ...(Object.fromEntries(COACH_ATTRIBUTES.map((a) => [a, level])) as Coach),
  ...over,
});
